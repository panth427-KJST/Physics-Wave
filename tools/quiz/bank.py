# ---------------- ตัวช่วยตรวจ ----------------
FIG4_THETA = [math.pi/2, math.pi, 3*math.pi/2, 9*math.pi/4]   # มุม kx ของ A B C D ในรูป f4 (รูป y = sin kx ณ ขณะนั้น)
def _dir(theta):
    """คลื่นไป +x: y(x,t) = sin(kx − ωt) → v_y = −ω cos(kx − ωt) ที่ t = 0"""
    vy = -math.cos(theta)
    return 'stop' if abs(vy) < 1e-9 else ('up' if vy > 0 else 'down')
def _state_at(phase_P, lag):
    ph = math.radians(phase_P - lag)          # y = sin φ, v ∝ cos φ
    y, v = math.sin(ph), math.cos(ph)
    if abs(y) < 1e-9: return 'up' if v > 0 else 'down'
    return 'crest' if y > 0 else 'trough'

